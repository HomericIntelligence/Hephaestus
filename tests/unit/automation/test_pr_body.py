"""Tests for hephaestus.automation.pr_body."""

from __future__ import annotations

import pytest

from hephaestus.automation.pr_body import replace_testing_section

_CANONICAL = """## Summary
Implements the requested changes for issue #7.

## Changes
See the PR diff for the full change set.

## Testing
`uv run pytest tests` — passed

## Closes
Closes #7

Generated by Hephaestus automation
"""


def test_replaces_only_the_testing_text() -> None:
    """Every other section stays byte for byte."""
    updated = replace_testing_section(_CANONICAL, "`bash scripts/run_ci_local.sh all` — passed")

    assert updated == (
        "## Summary\n"
        "Implements the requested changes for issue #7.\n"
        "\n"
        "## Changes\n"
        "See the PR diff for the full change set.\n"
        "\n"
        "## Testing\n"
        "`bash scripts/run_ci_local.sh all` — passed\n"
        "\n"
        "## Closes\n"
        "Closes #7\n"
        "\n"
        "Generated by Hephaestus automation\n"
    )


def test_repeated_receipt_is_idempotent() -> None:
    """The same receipt yields the same body, so a caller can skip the write."""
    once = replace_testing_section(_CANONICAL, "`uv run pytest tests` — passed")

    assert once == replace_testing_section(once, "`uv run pytest tests` — passed")


def test_multi_line_receipt_replaces_the_whole_section() -> None:
    """A multi-line receipt replaces every old line of the section."""
    body = _CANONICAL.replace("`uv run pytest tests` — passed", "old line one\nold line two")

    updated = replace_testing_section(body, "new line one\nnew line two")

    assert "## Testing\nnew line one\nnew line two\n\n## Closes\n" in updated
    assert "old line" not in updated


def test_operator_edits_outside_the_section_are_kept() -> None:
    """An operator note in another section survives the refresh."""
    body = _CANONICAL.replace(
        "See the PR diff for the full change set.",
        "See the PR diff. Operator note: keep the ADR link.",
    )

    updated = replace_testing_section(body, "`uv run pytest tests` — passed; 12 passed")

    assert "Operator note: keep the ADR link." in updated
    assert "`uv run pytest tests` — passed; 12 passed" in updated


def test_missing_section_is_added_before_the_closes_line() -> None:
    """A body without a Testing section gains one in the canonical order."""
    body = "## Summary\nS\n\n## Closes\nCloses #7\n"

    updated = replace_testing_section(body, "`uv run pytest tests` — passed")

    assert updated == (
        "## Summary\nS\n\n## Testing\n`uv run pytest tests` — passed\n\n## Closes\nCloses #7\n"
    )


def test_missing_section_and_closes_line_appends_at_the_end() -> None:
    """A body with neither heading gains the section after its last line."""
    updated = replace_testing_section("## Summary\nS\n", "`uv run pytest tests` — passed")

    assert updated == "## Summary\nS\n\n## Testing\n`uv run pytest tests` — passed\n"


def test_body_without_a_trailing_newline_keeps_its_shape() -> None:
    """The edit does not invent a line ending the body did not have."""
    updated = replace_testing_section(
        "## Testing\nold\n\n## Closes\nCloses #7", "`uv run pytest tests` — passed"
    )

    assert updated == "## Testing\n`uv run pytest tests` — passed\n\n## Closes\nCloses #7"


@pytest.mark.parametrize("testing", ["", "   ", "\n"])
def test_blank_receipt_returns_the_body_unchanged(testing: str) -> None:
    """A caller with nothing to state makes no claim."""
    assert replace_testing_section(_CANONICAL, testing) == _CANONICAL
